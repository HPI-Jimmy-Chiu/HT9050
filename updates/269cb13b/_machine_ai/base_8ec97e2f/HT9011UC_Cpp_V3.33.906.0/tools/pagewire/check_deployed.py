def rd(p):
    return io.open(p, "rb").read()


def discover(web):
    """{page stem: [js, ...]} -- EVERY script of ours the page loads.

    AI(W906-NL-SCOPE) 20260916: 原本回傳 `m.group(1)`，也就是**第一個**命中。
    引擎架構下一頁會載三支（`recipe_client` / `wire_engine` / `wire_<page>`），
    只取第一個等於**每頁只檢查 wire_engine**，14 支 per-page 接線腳本
    連 `node --check` 都沒跑到。回傳整串才對得起「守住接線」這句話。
    """
    out = {}
    if not os.path.isdir(web):
        return out
    for name in sorted(os.listdir(web)):
        if not name.lower().endswith(".html"):
            continue
        hits = OURS_RE.findall(io.open(os.path.join(web, name), encoding="utf-8",
                                       errors="replace").read())
        if hits:
            out[name[:-5]] = sorted(set(hits))
    return out


def run(cfg, quiet=False):
    """Returns the list of failure strings. Empty list = all green."""
    fails = []

    def bad(msg):
        fails.append(msg)
        if not quiet:
            print("  FAIL  " + msg)

    def ok(msg):
        if not quiet:
            print("  ok    " + msg)

    web, cweb, cjs = cfg["web"], cfg["client_web"], cfg["client_js"]
    # AI(W906-WIRE-SYS) 20260917：從 cfg 拿，**不要**讀全域 REAL ——
    #   selftest 傳的是暫存 fixture，讀全域會讓自我測試被真實的樹影響。
    gen = cfg.get("generated") or ""
    pages = discover(web)
    if not pages:
        bad("no wired pages found under %s -- is the path right?" % web)
        return fails
    if not quiet:
        print("discovered %d wired page(s)\n" % len(pages))
        print("=== 1. script order inside each deployed page ===")
    for stem, jss in sorted(pages.items()):
        txt = io.open(os.path.join(web, stem + ".html"), encoding="utf-8",
                      errors="replace").read()
        # AI(W906-WIRE-SYS) 20260917：鎖在 src="..." 裡，不要用裸檔名。
        #   txt.find(js) 會命中**註解裡的「提到」**。實測 4 頁中招：
        #     HW.IoSetView.html:627 與 main.html:298 的註解 -> 假陽性（該綠報紅）；
        #     Setup.Contact.html / Setup.HotPlate.html 的註解提到 CLIENT_LIB，
        #     把 i_lib 拉到檔案更前面 -> **假陰性**（該紅變綠）。
        #   假陽性會被人判掉，假陰性沒有人會來找。
        def at(name):
            return txt.find('src="%s"' % name)
        i_lib = at(CLIENT_LIB)
        for js in jss:
            i_own = at(js)
            if i_lib < 0:
                bad("%s.html references %s but never loads %s"
                    % (stem, js, CLIENT_LIB))
            elif i_lib > i_own:
                bad("%s.html loads %s AFTER %s -- order is load-bearing"
                    % (stem, CLIENT_LIB, js))
            else:
                ok("%-22s client then %s" % (stem, js))

    if not quiet:
        print("\n=== 2. each js parses, and matches ITS OWN authoritative source ===")
    for js in sorted({j for v in pages.values() for j in v} | {CLIENT_LIB}):
        a, b = os.path.join(web, js), os.path.join(cjs, js)
        if not os.path.isfile(a):
            bad("%s missing from web/page" % js)
            continue
        if subprocess.call(["node", "--check", a], stdout=subprocess.DEVNULL,
                           stderr=subprocess.DEVNULL, shell=True) != 0:
            bad("%s does not parse (node --check)" % js)
        # AI(W906-WIRE-SYS) 20260917：跟**各自的權威來源**比。
        #   接線檔多數是 merge_wire.py 產生的（對本機 64 個工單與實體 ini
        #   重新分類過），跟他的 client/ 來源本來就不同 —— 一律比 client/
        #   會讓 17 支恆紅，而恆紅的檢查等於沒有檢查。
        #   但不能直接刪：這一項真正要守的是「有人手改了線上檔」。
        g = os.path.join(gen, js) if gen else ""
        if os.path.isfile(g):
            if rd(a) != rd(g):
                bad("%s differs between web/page and our generated wire/ "
                    "-- someone hand-edited the deployed copy, or the deploy is stale" % js)
            else:
                ok("%-30s parses, web == generated (%d bytes)" % (js, len(rd(a))))
        else:
            # AI(W906-A6) 20260924：原樣通過的檔（不是我們產生的）以 web/page 為準（P5），
            #   不再拿凍結在 0917 的 client repo 比 —— 那個比較恆紅，等於沒有檢查。
            #   只要求它存在（上面）而且能解析（上面的 node --check）。
            ok("%-30s parses (pass-through; web/page is the authority) (%d bytes)" % (js, len(rd(a))))

    if not quiet:
        print("\n=== 3. OURS lists every deployed js, in BOTH sync_web.py copies ===")
    want = sorted({j for v in pages.values() for j in v} | {CLIENT_LIB})
    for sp in cfg["syncs"]:
        if not os.path.isfile(sp):
            bad("sync file missing: %s" % sp)
            continue
        txt = io.open(sp, encoding="utf-8", errors="replace").read()
        miss = [js for js in want if ("page/" + js) not in txt]
        if miss:
            bad("%s: OURS is missing %s -- the next sync deletes it"
                % (os.path.basename(sp), ", ".join(miss)))
        else:
            ok("%-46s all %d listed" % (os.path.basename(sp), len(want)))

    if not quiet:
        print("\n=== 4. (informational) pages only in the client repo, not in web/page ===")
        # AI(W906-A6) 20260924：只列不判。要搬哪一頁由人決定（例：做 State Record 按鈕時才搬
        #   Main.gbControlBtn.html），不整批同步。
        only = []
        if os.path.isdir(cweb):
            only = sorted(n for n in os.listdir(cweb)
                          if n.lower().endswith(".html") and not os.path.isfile(os.path.join(web, n)))
        print("  info  %d page(s) exist only in the client repo%s"
              % (len(only), (": " + ", ".join(only[:12]) + (" ..." if len(only) > 12 else "")) if only else ""))
    return fails


