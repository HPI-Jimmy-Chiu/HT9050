GOOD_PAGE = ('<html><body>\n<p>x</p>\n'
             '<script src="ht9045_recipe_client.js"></script>\n'
             '<script src="ht9045_%s_wire.js"></script>\n</body></html>\n')
GOOD_JS = "(function(){ 'use strict'; })();\n"


def build_fixture(root, break_what):
    web = os.path.join(root, "web"); cweb = os.path.join(root, "cweb")
    cjs = os.path.join(root, "cjs"); syncdir = os.path.join(root, "sync")
    gen = os.path.join(root, "gen")   # AI(W906-WIRE-SYS) 20260917: 我們產生的那一份
    for d in (web, cweb, cjs, syncdir, gen):
        os.makedirs(d)
    js = "ht9045_alpha_wire.js"
    page = GOOD_PAGE % "alpha"
    if break_what == "order":
        page = page.replace(
            '<script src="ht9045_recipe_client.js"></script>\n'
            '<script src="%s"></script>\n' % js,
            '<script src="%s"></script>\n'
            '<script src="ht9045_recipe_client.js"></script>\n' % js)
    io.open(os.path.join(web, "Alpha.html"), "w", newline="").write(page)
    io.open(os.path.join(cweb, "Alpha.html"), "w", newline="").write(
        page if break_what != "page_drift" else page.replace("<p>x</p>", "<p>y</p>"))
    for name in (js, CLIENT_LIB):
        body = GOOD_JS
        if break_what == "parse" and name == js:
            body = "(function(){ this is not javascript\n"
        io.open(os.path.join(web, name), "w", newline="").write(body)
        io.open(os.path.join(cjs, name), "w", newline="").write(
            body if not (break_what == "js_drift" and name == js)
            else body + "// drifted\n")
        # AI(W906-WIRE-SYS) 20260917：gen_drift 專用 —— 只有這個案例才把檔案
        #   放進 generated/，這樣其他案例仍走「原樣通過」那條分支（維持原語意）。
        if break_what == "gen_drift" and name == js:
            io.open(os.path.join(gen, name), "w", newline="").write(
                body + "// generated differs from what is deployed\n")
    listed = [CLIENT_LIB] + ([] if break_what == "ours" else [js])
    sp = os.path.join(syncdir, "sync_web.py")
    io.open(sp, "w", newline="").write(
        "OURS = {\n" + "".join('    "page/%s",\n' % n for n in listed) + "}\n")
    return {"web": web, "client_web": cweb, "client_js": cjs, "syncs": [sp],
            "generated": gen}


def selftest():
    # AI(W906-A6) 20260924：js_drift／page_drift 兩個情境拿掉 —— 「和 client repo 不同」
    #   已經不是違規（使用者裁決 A6，web/page 是唯一權威）。其餘四個違規照舊必須被抓到。
    cases = [("(nothing broken)", 0), ("order", 1), ("parse", 1),
             ("gen_drift", 1), ("ours", 1)]
    bad = 0
    print("selftest -- each case builds a fixture and runs the REAL checks\n")
    for what, expect_min in cases:
        root = tempfile.mkdtemp(prefix="pagewire_selftest_")
        try:
            cfg = build_fixture(root, None if expect_min == 0 else what)
            fails = run(cfg, quiet=True)
            got = len(fails)
            hit = (got == 0) if expect_min == 0 else (got >= 1)
            print("  %-4s %-18s -> %d failure(s)%s"
                  % ("PASS" if hit else "FAIL", what, got,
                     "" if not fails else "  | " + fails[0][:74]))
            if not hit:
                bad += 1
        finally:
            shutil.rmtree(root, ignore_errors=True)
    print("\n%s" % ("selftest OK: every check can fail, and passes when nothing is broken"
                    if not bad else "SELFTEST FAILED on %d case(s)" % bad))
    return 1 if bad else 0


def main(argv):
    if "--selftest" in argv:
        return selftest()
    fails = run(REAL)
    print("\n%s" % ("ALL GREEN" if not fails else "%d PROBLEM(S)" % len(fails)))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
